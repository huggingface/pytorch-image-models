def load_results(path: Path) -> Dict[str, List[Dict[str, str]]]:
    """Load an ImageNet results csv, keyed by full ``arch.tag`` name (one row per evaluated image size)."""
    rows = defaultdict(list)
    if not path.exists():
        return rows
    with open(path, newline='') as f:
        for row in csv.DictReader(f):
            rows[row['model']].append(row)
    return rows


def load_benchmark(
        results_dir: Path,
        architectures: Sequence[str],
        path: Optional[Path] = None,
) -> Tuple[Optional[Path], Dict[Tuple[str, int], Dict[str, str]]]:
    """Load an inference benchmark csv, keyed by ``(arch, img_size)``.

    Params and GMACs do not depend on the benchmark hardware, so when no path is given the csv covering the most
    currently registered architectures is used (the newest benchmark runs cover the most models).
    """
    archs = set(architectures)
    best = None
    if path is None:
        for p in sorted(results_dir.glob('benchmark-infer-*.csv')):
            with open(p, newline='') as f:
                rows = list(csv.DictReader(f))
            if 'infer_gmacs' not in rows[0] or 'param_count' not in rows[0]:
                continue
            coverage = len({r['model'] for r in rows} & archs)
            if best is None or coverage > best[0]:
                best = (coverage, p, rows)
        if best is None:
            return None, {}
        path, rows = best[1], best[2]
    else:
        with open(path, newline='') as f:
            rows = list(csv.DictReader(f))
    return path, {(r['model'], int(r['infer_img_size'])): r for r in rows}


