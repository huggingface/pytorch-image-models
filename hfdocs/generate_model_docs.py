def wrap_markdown(text: str, width: int = 120) -> str:
    """Wrap prose and list item lines of generated markdown to the docs line length.

    Tables, headings, code blocks and lines that are already short enough are left as is. Inline code and links are
    never split.

    Args:
        text: Markdown text.
        width: Maximum line length.

    Returns:
        The wrapped text.
    """
    out = []
    in_code = False
    for line in text.split('\n'):
        if line.lstrip().startswith('```'):
            in_code = not in_code
            out.append(line)
            continue
        if in_code or len(line) <= width or line.lstrip().startswith(('|', '#')):
            out.append(line)
            continue
        stripped = line.lstrip()
        indent = line[:len(line) - len(stripped)]
        bullet = re.match(r'([-*] |\d+\. )', stripped)
        subsequent = indent + ' ' * (len(bullet.group(1)) if bullet else 0)
        out.append(textwrap.fill(
            stripped,
            width=width,
            initial_indent=indent,
            subsequent_indent=subsequent,
            break_long_words=False,
            break_on_hyphens=False,
        ))
    return '\n'.join(out)


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument(
        '--families', nargs='+', default=None, choices=sorted(FAMILIES), metavar='SLUG',
        help='families to generate, default all. The support matrix is only updated when all are generated')
    parser.add_argument('--output-dir', type=Path, default=_DOCS_SOURCE / 'models', help='family page directory')
    parser.add_argument('--results-dir', type=Path, default=_REPO_ROOT / 'results', help='results csv directory')
    parser.add_argument('--benchmark-csv', type=Path, default=None, help='benchmark csv for params / GMACs')
    parser.add_argument(
        '--matrix-file', type=Path, default=None,
        help='also write the support matrix to this file')
    parser.add_argument(
        '--model-api-page', type=Path, default=_DOCS_SOURCE / 'model_api.mdx',
        help='page to splice the support matrix into, if it has the generated support matrix markers')
    parser.add_argument('--no-probe', action='store_true', help='skip the model API probe (no support tables)')
    parser.add_argument('--check', action='store_true', help='do not write, exit 1 if any output is out of date')
    parser.add_argument('-v', '--verbose', action='store_true', help='print data issues')
    args = parser.parse_args(argv)

    if _REPO_ROOT not in Path(timm.__file__).resolve().parents:
        print(f'timm imported from {timm.__file__}, not this repository. Run with PYTHONPATH={_REPO_ROOT}.',
              file=sys.stderr)
        return 2
    logging.getLogger('timm').setLevel(logging.ERROR)
    warnings.filterwarnings('ignore')
    torch.set_grad_enabled(True)

    t0 = time.perf_counter()
    slugs = args.families or list(FAMILIES)
    results = load_results(args.results_dir / 'results-imagenet.csv')
    bench_path, benchmark = load_benchmark(args.results_dir, timm.list_models(), args.benchmark_csv)
    print(f'timm {timm.__version__} from {Path(timm.__file__).parent}, benchmark data {bench_path}')

    families = []
    outputs: Dict[Path, str] = {}
    for slug in slugs:
        print(f'{slug}:')
        data = collect_family(slug, FAMILIES[slug], results, benchmark, probe=not args.no_probe)
        families.append(data)
        outputs[args.output_dir / f'{slug}.mdx'] = render_family(data, results)
        print(f'  {len(data.archs)} architectures, {len(data.weights)} weights, {len(data.papers)} papers, '
              f'{len(data.issues)} data issues')
        if args.verbose:
            for issue in data.issues:
                print(f'    {issue}')

    if args.no_probe or set(slugs) != set(FAMILIES):
        # the matrix covers every family, a partial run would drop rows
        print('support matrix not updated (needs all families and the probe)')
    else:
        matrix = render_support_matrix(families)
        if args.matrix_file is not None:
            outputs[args.matrix_file] = matrix
        spliced = splice_matrix(args.model_api_page, matrix)
        if spliced is not None:
            outputs[args.model_api_page] = spliced

    stale = []
    for path, text in outputs.items():
        text = wrap_markdown(text)
        if path.exists() and path.read_text() == text:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    action = 'out of date' if args.check else 'written'
    for path in stale:
        print(f'{action}: {path}')
    print(f'done in {time.perf_counter() - t0:.1f}s')
    return 1 if args.check and stale else 0


if __name__ == '__main__':
    sys.exit(main())
