def _md(text: str) -> str:
    """Escape text for a markdown table cell / MDX prose."""
    return text.replace('|', '\\|').replace('<', '&lt;').replace('{', '&#123;').replace('}', '&#125;')


def _table(headers: Sequence[str], rows: Sequence[Sequence[str]], align: Optional[Sequence[str]] = None) -> str:
    align = align or ['l'] * len(headers)
    sep = ['---:' if a == 'r' else '---' for a in align]
    lines = ['| ' + ' | '.join(headers) + ' |', '|' + '|'.join(sep) + '|']
    lines += ['| ' + ' | '.join(r) + ' |' for r in rows]
    return '\n'.join(lines)


def _feature_cell(r: ProbeResult, key: str) -> str:
    value = r.status.get(key, NO)
    cell = _SYMBOLS[value]
    if key == 'features_only' and value == YES and r.feature_reductions:
        cell += ' (strides ' + ', '.join(str(x) for x in r.feature_reductions) + ')'
    return cell


def render_family(data: FamilyData, results: Dict[str, List[Dict[str, str]]]) -> str:
    """Render the MDX page of a family."""
    spec = data.spec
    modules = spec['modules']
    module_links = ', '.join(f'[`timm/models/{m}.py`]({_GITHUB_BLOB}/timm/models/{m}.py)' for m in modules)
    num_in1k = sum(1 for w in data.weights if w in results)
    out = [
        _GENERATED_NOTE,
        '',
        f'# {spec["title"]}',
        '',
        f'**Category:** {spec["category"]} · **Code:** {module_links} · **Architectures:** {len(data.archs)} · '
        f'**Pretrained weights:** {len(data.weights)} ({num_in1k} with ImageNet-1k results)',
        '',
        spec['description'],
        '',
    ]

    def _paper_item(p: Paper) -> str:
        title = _md(p.title) if p.title else p.key.replace('arxiv:', 'arXiv:')
        return f'* [{title}]({p.url})' if p.url else f'* {title}'

    out += ['## Papers', '']
    if data.papers:
        out += [_paper_item(p) for p in data.papers]
    else:
        out.append('The module docstring does not reference any papers.')
    if data.weight_papers:
        out += ['', 'Referenced by pretrained weights:', '']
        out += [_paper_item(p) for p in data.weight_papers]
    out.append('')

    out += [
        '## Usage',
        '',
        'See the [Quickstart](../quickstart) for loading pretrained weights, image preprocessing and fine-tuning, '
        'and [Feature Extraction](../feature_extraction) for using the models as backbones.',
        '',
    ]
    if data.example:
        out += [
            '```py',
            '>>> import timm',
            f">>> model = timm.create_model('{data.example}', pretrained=True)",
            '>>> data_config = timm.data.resolve_model_data_config(model)',
            '```',
            '',
        ]

    out += ['## Model API support', '']
    if data.probes:
        classes = sorted(data.probes)
        headers = ['Feature'] + [f'`{c}`' for c in classes]
        rows = []
        for key, label, anchor in FEATURES:
            link = f'[{label}]({_MODEL_API_PAGE}#{anchor})'
            rows.append([link] + [_feature_cell(data.probes[c], key) for c in classes])
        out += [_table(headers, rows), '']
        probed = ', '.join(
            f'`{c}` with `{data.probes[c].arch}` at {_fmt_size(data.probes[c].img_size)}' for c in classes)
        out += [
            f'{_LEGEND} Checked by running each feature on a randomly initialized model ({probed}), other '
            f'architectures of the same class are expected to behave the same. See the '
            f'[Model API]({_MODEL_API_PAGE}) page for details.',
            '',
        ]
    else:
        out += ['Not probed.', '']

    out += ['## Architectures', '']
    multi_class = len({a.model_class for a in data.archs}) > 1
    headers = ['Architecture'] + (['Class'] if multi_class else []) + [
        'Params (M)', 'GMACs', 'Input size', 'Pretrained weights']
    align = ['l'] + (['l'] if multi_class else []) + ['r', 'r', 'r', 'r']
    rows = []
    for a in data.archs:
        rows.append([f'`{a.name}`'] + ([f'`{a.model_class}`'] if multi_class else []) + [
            f'{a.params_m:.2f}' if a.params_m is not None else '-',
            a.gmacs or '-',
            _fmt_size(a.input_size),
            str(a.num_pretrained),
        ])
    out += [
        _table(headers, rows, align),
        '',
        'GMACs and parameter counts are for the default input size and classifier of each architecture, from the '
        '[benchmark results](https://github.com/huggingface/pytorch-image-models/tree/main/results).',
        '',
    ]

    out += ['## Pretrained weights', '']
    rows = []
    for w in data.weights:
        cfg = get_pretrained_cfg(w)
        row = _top1(w, results)
        if cfg.hf_hub_id:
            hub_text = 'timm' if cfg.hf_hub_id == f'timm/{w}' else cfg.hf_hub_id
            hub = f'[{_md(hub_text)}]({_HUB_URL}/{cfg.hf_hub_id})'
        elif cfg.url:
            hub = f'[original]({cfg.url})'
        else:
            hub = '-'
        input_size = _fmt_size(cfg.input_size)
        if cfg.test_input_size and tuple(cfg.test_input_size) != tuple(cfg.input_size):
            input_size += f' (test {_fmt_size(cfg.test_input_size)})'
        rows.append([
            f'`{w}`',
            input_size,
            row['top1'] if row else '-',
            row['img_size'] if row else '-',
            str(cfg.num_classes) if cfg.num_classes else 'none',
            _md(cfg.license or '-'),
            hub,
        ])
    out += [
        _table(['Weight', 'Input size', 'Top-1 (%)', 'Eval size', 'Classes', 'License', 'Hub'], rows,
               ['l', 'r', 'r', 'r', 'r', 'l', 'l']),
        '',
        'Top-1 is ImageNet-1k validation accuracy from [`results-imagenet.csv`]'
        '(https://github.com/huggingface/pytorch-image-models/blob/main/results/results-imagenet.csv) at the '
        'listed eval size, - if the weight has no ImageNet-1k result (e.g. pretraining or image-text weights). '
        'Classes is the size of the pretrained classifier, none for weights without one.',
        '',
    ]

    if data.bibtex:
        out += ['## Citation', '', '```bibtex', '\n\n'.join(data.bibtex), '```', '']
    return '\n'.join(out)


def render_support_matrix(families: Sequence[FamilyData]) -> str:
    """Render the Model API support matrix (one row per family and model class)."""
    keys = [k for k, _, _ in FEATURES]
    headers = ['Family', 'Class'] + [_MATRIX_HEADERS[k] for k in keys]
    rows = []
    for data in families:
        for c in sorted(data.probes):
            r = data.probes[c]
            rows.append([f'[{_md(data.spec["title"])}](models/{data.slug})', f'`{c}`'] + [
                _SYMBOLS[r.status.get(k, NO)] for k in keys])
    return '\n'.join([
        _GENERATED_NOTE,
        '',
        _table(headers, rows),
        '',
        f'{_LEGEND} Each class is checked by running every feature on a randomly initialized model of '
        'its smallest (non-test) architecture.',
        '',
    ])


def splice_matrix(page: Path, matrix: str) -> Optional[str]:
    """Return ``page`` with ``matrix`` between the generated support matrix markers, or None if not applicable."""
    if not page.exists():
        return None
    text = page.read_text()
    begin, end = text.find(_MATRIX_BEGIN), text.find(_MATRIX_END)
    if begin < 0 or end < begin:
        return None
    return text[:begin + len(_MATRIX_BEGIN)] + '\n' + matrix + text[end:]


