# Probe outcomes. SQUARE: works for square sizes other than the default but not for a non-square size.
YES, NO, SQUARE, NOT_NEEDED = 'yes', 'no', 'square', 'n/a'
_SYMBOLS = {YES: '✓', NO: '✗', SQUARE: '✓ (square)', NOT_NEEDED: '–'}
