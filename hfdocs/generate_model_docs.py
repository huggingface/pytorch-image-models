@dataclass
class ProbeResult:
    """Model API probe outcome for one model class (probed on one representative architecture)."""
    model_class: str
    arch: str
    img_size: Tuple[int, int]
    status: Dict[str, str] = field(default_factory=dict)
    errors: Dict[str, str] = field(default_factory=dict)
    feature_reductions: List[int] = field(default_factory=list)
    seconds: float = 0.


def _first_tensor(out: Any) -> torch.Tensor:
    if isinstance(out, (tuple, list)):
        out = out[0]
    if isinstance(out, dict):
        out = next(iter(out.values()))
    if not isinstance(out, torch.Tensor):
        raise TypeError(f'unexpected output type {type(out).__name__}')
    return out


def _forward_ok(model: torch.nn.Module, size: Tuple[int, int], batch_size: int = 1) -> None:
    """Run a forward pass, raise if it fails or a classifier output is not ``(batch_size, num_classes)``."""
    out = _first_tensor(model(torch.randn(batch_size, 3, *size)))
    num_classes = getattr(model, 'num_classes', 0)
    if hasattr(model, 'reset_classifier') and num_classes:
        if tuple(out.shape) != (batch_size, num_classes):
            raise ValueError(f'output shape {tuple(out.shape)}, expected {(batch_size, num_classes)}')
    elif out.shape[0] != batch_size:
        raise ValueError(f'output shape {tuple(out.shape)}')


def _size_support(model: torch.nn.Module, square: Tuple[int, int], rect: Tuple[int, int]) -> str:
    """Forward at a non-default square size, then a non-square size. Raise if the square size fails."""
    _forward_ok(model, square)
    try:
        _forward_ok(model, rect)
    except Exception:
        return SQUARE
    return YES


def _err(e: BaseException) -> str:
    return f'{type(e).__name__}: {str(e).splitlines()[0][:200] if str(e) else ""}'


def probe_model_api(arch: str, model_class: str) -> ProbeResult:
    """Functionally probe the model API of a randomly initialized model on CPU.

    Signature or ``hasattr`` checks alone are unreliable (some classes accept and silently drop unknown kwargs, some
    methods exist but assert), so each feature counts only if a small call using it actually works. Probe steps catch
    any exception on purpose, a model failing a feature for any reason means the feature is not usable.

    Args:
        arch: Architecture name, ideally the smallest of its class.
        model_class: Name of the model class, for reporting.

    Returns:
        The probe result.
    """
    t0 = time.perf_counter()
    cfg = get_pretrained_cfg(arch)
    h, w = cfg.input_size[-2:]
    res = ProbeResult(model_class=model_class, arch=arch, img_size=(h, w))
    status, errors = res.status, res.errors

    torch.manual_seed(0)
    base = timm.create_model(arch, pretrained=False).eval()
    with torch.no_grad():
        _forward_ok(base, (h, w))  # must work, anything below is meaningless otherwise

    # A size step that is a multiple of the network stride (or patch size), at least 32 px.
    stride = 32
    feature_info = getattr(base, 'feature_info', None)
    if isinstance(feature_info, (list, tuple)) and feature_info and feature_info[-1].get('reduction'):
        stride = int(feature_info[-1]['reduction'])
    step = stride * math.ceil(32 / stride)
    square, rect = (h + step, w + step), (h + step, w + 2 * step)

    def _check(key: str, fn) -> None:
        try:
            with torch.no_grad():
                status[key] = fn()
        except Exception as e:
            status[key] = NO
            errors[key] = _err(e)

    _check('flexible_input', lambda: _size_support(base, square, rect))
    flexible = status['flexible_input'] != NO

    def _features_only():
        model = timm.create_model(arch, pretrained=False, features_only=True).eval()
        feats = model(torch.randn(1, 3, h, w))
        reductions = [int(r) for r in model.feature_info.reduction()]  # for the selected out_indices
        if not isinstance(feats, (list, tuple)) or not feats or len(feats) != len(reductions):
            raise ValueError('unexpected feature output')
        res.feature_reductions = reductions
        return YES
    _check('features_only', _features_only)

    def _forward_intermediates():
        feats = base.forward_intermediates(torch.randn(1, 3, h, w), intermediates_only=True)
        if not isinstance(feats, (list, tuple)) or not feats or not all(isinstance(f, torch.Tensor) for f in feats):
            raise ValueError('unexpected intermediates output')
        return YES
    _check('forward_intermediates', _forward_intermediates)

    def _prune():
        model = copy.deepcopy(base)
        num_params = sum(p.numel() for p in model.parameters())
        model.prune_intermediate_layers(indices=[0], prune_norm=True, prune_head=True)
        feats = model.forward_intermediates(torch.randn(1, 3, h, w), indices=[0], intermediates_only=True)
        if len(feats) != 1:
            raise ValueError(f'{len(feats)} intermediates after pruning to one')
        if sum(p.numel() for p in model.parameters()) >= num_params:
            raise ValueError('no parameters removed')
        return YES
    _check('prune_intermediate_layers', _prune)

    def _set_input_size():
        if not hasattr(base, 'set_input_size'):
            if flexible:
                return NOT_NEEDED
            raise AttributeError('no set_input_size()')
        try:
            model = copy.deepcopy(base)
            model.set_input_size(img_size=rect)
            _forward_ok(model, rect)
            return YES
        except Exception:
            model = copy.deepcopy(base)
            model.set_input_size(img_size=square)
            _forward_ok(model, square)
            return SQUARE
    _check('set_input_size', _set_input_size)

    def _dynamic_img_size():
        try:
            model = timm.create_model(arch, pretrained=False, dynamic_img_size=True).eval()
            enabled = any(getattr(m, 'dynamic_img_size', None) is True for m in model.modules())
            if not enabled:
                raise ValueError('dynamic_img_size=True accepted but not enabled')
        except Exception:
            if flexible:
                return NOT_NEEDED
            raise
        return _size_support(model, square, rect)
    _check('dynamic_img_size', _dynamic_img_size)

    def _group_matcher():
        layer_map = group_parameters(base, base.group_matcher(coarse=False), reverse=True)
        if len(set(layer_map.values())) < 2:
            raise ValueError('all parameters in one group')
        return YES
    _check('group_matcher', _group_matcher)

    def _grad_checkpointing():
        # Checkpointed segments are re-run during backward, count module forward calls to see that it happens.
        model = copy.deepcopy(base).train()
        model.set_grad_checkpointing(True)
        calls = [0]

        def _hook(*args):
            calls[0] += 1

        handles = [m.register_forward_hook(_hook) for m in model.modules()]
        try:
            with torch.enable_grad():
                out = model(torch.randn(2, 3, h, w))
                outs = out if isinstance(out, (tuple, list)) else (out,)
                loss = sum(o.float().mean() for o in outs if isinstance(o, torch.Tensor))
                forward_calls = calls[0]
                loss.backward()
        finally:
            for handle in handles:
                handle.remove()
        if calls[0] == forward_calls:
            raise ValueError('set_grad_checkpointing(True) accepted but nothing is recomputed in backward')
        return YES
    _check('grad_checkpointing', _grad_checkpointing)

    def _reset_classifier():
        model = copy.deepcopy(base)
        model.reset_classifier(7)
        _forward_ok(model, (h, w))
        if model.num_classes != 7:
            raise ValueError('num_classes not updated')
        model.reset_classifier(0)
        out = _first_tensor(model(torch.randn(1, 3, h, w)))
        if out.ndim != 2:
            raise ValueError(f'reset_classifier(0) output shape {tuple(out.shape)}')
        return YES
    _check('reset_classifier', _reset_classifier)

    res.seconds = time.perf_counter() - t0
    return res


